// https://github.com/openstack/nova/blob/18898d20148c48b4671dbae0a461d723859380c5/nova/tests/unit/test_crypto.py#L144-L196
func TestFingerprintMatchesNovaVectors(t *testing.T) {
	for _, test := range []struct {
		name, key, want string
	}{
		{name: "rsa", key: novaRSAKey, want: "e7:66:a1:2c:4f:90:6e:11:19:da:ac:c2:69:e1:ad:89"},
		{name: "dsa", key: novaDSAKey, want: "b9:dc:ac:57:df:2a:2b:cf:65:a8:c3:4e:9d:4a:82:3c"},
		{name: "ecdsa", key: novaECDSAKey + " Generated-by-Nova", want: "16:6a:c9:ec:80:4d:17:3e:d5:3b:6f:c0:d7:15:04:40"},
		{name: "comment with spaces", key: novaECDSAKey + " Generated by Nova",
			want: "16:6a:c9:ec:80:4d:17:3e:d5:3b:6f:c0:d7:15:04:40"},
	} {
		t.Run(test.name, func(t *testing.T) {
			fingerprint, err := sshkey.Fingerprint(test.key)

			require.NoError(t, err)
			assert.Equal(t, test.want, fingerprint)
		})
	}
}

func TestFingerprintRejectsMalformedKeys(t *testing.T) {
	blob := func(parts ...[]byte) string {
		var buffer bytes.Buffer
		for _, part := range parts {
			buffer.Write([]byte{0, 0, 0, byte(len(part))})
			buffer.Write(part)
		}
		return base64.StdEncoding.EncodeToString(buffer.Bytes())
	}
	ed25519Blob := strings.Fields(ed25519Key)[1]
	trailing, err := base64.StdEncoding.DecodeString(ed25519Blob)
	require.NoError(t, err)
	_, err = sshkey.Fingerprint(ed25519Key)
	require.NoError(t, err)

	for name, key := range map[string]string{
		"empty":            "",
		"type only":        "ssh-ed25519",
		"invalid base64":   "ssh-ed25519 not-base64!",
		"mismatched type":  "ssh-rsa " + ed25519Blob,
		"trailing data":    "ssh-ed25519 " + base64.StdEncoding.EncodeToString(append(trailing, 0)),
		"short ed25519":    "ssh-ed25519 " + blob([]byte("ssh-ed25519"), make([]byte, 31)),
		"even exponent":    "ssh-rsa " + blob([]byte("ssh-rsa"), []byte{2}, []byte{0x7f, 0xff}),
		"wrong curve":      "ecdsa-sha2-nistp384 " + blob([]byte("ecdsa-sha2-nistp384"), []byte("nistp256"), []byte{4}),
		"unsupported type": "ssh-foo " + blob([]byte("ssh-foo")),
		"leading space":    " " + ed25519Key,
	} {
		_, err := sshkey.Fingerprint(key)

		assert.ErrorIs(t, err, sshkey.ErrInvalidPublicKey, name)
	}
}

func TestGenerateIsDeterministicForTheSameRandomStream(t *testing.T) {
	random := func(seed byte) *rand.ChaCha8 {
		return rand.NewChaCha8([32]byte{seed})
	}

	privateKey, publicKey, err := sshkey.Generate(random(1))
	require.NoError(t, err)
	repeatedPrivate, repeatedPublic, err := sshkey.Generate(random(1))
	require.NoError(t, err)
	_, otherPublic, err := sshkey.Generate(random(2))
	require.NoError(t, err)

	assert.Equal(t, privateKey, repeatedPrivate)
	assert.Equal(t, publicKey, repeatedPublic)
	assert.NotEqual(t, publicKey, otherPublic)
	block, rest := pem.Decode([]byte(privateKey))
	require.NotNil(t, block)
	assert.Empty(t, rest)
	assert.Equal(t, "RSA PRIVATE KEY", block.Type)
	key, err := x509.ParsePKCS1PrivateKey(block.Bytes)
	require.NoError(t, err)
	assert.Equal(t, 2048, key.N.BitLen())
	assert.Equal(t, 65537, key.E)
	fields := strings.Split(publicKey, " ")
	require.Len(t, fields, 3)
	assert.Equal(t, "ssh-rsa", fields[0])
	assert.Equal(t, "Generated-by-Nova", fields[2])
	wire, err := base64.StdEncoding.DecodeString(fields[1])
	require.NoError(t, err)
	assert.True(t, bytes.HasSuffix(wire, key.N.Bytes()))
	digest := md5.Sum(wire)
	fingerprint, err := sshkey.Fingerprint(publicKey)
	require.NoError(t, err)
	assert.Equal(t, hex.EncodeToString(digest[:]), strings.ReplaceAll(fingerprint, ":", ""))
}
